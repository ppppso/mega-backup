CSRF = re.compile(r'name="csrf" value="([^"]+)"')


class Base(unittest.TestCase):
    def setUp(self):
        for d in ("config", "current", "repo", "restore"):
            shutil.rmtree(os.path.join(T, d), ignore_errors=True)
            os.makedirs(os.path.join(T, d))
        for f in os.listdir(STATE):
            os.unlink(os.path.join(STATE, f))
        open(os.path.join(STATE, "server"), "w").close()
        with open(os.environ["RESTIC_PASSWORD_FILE"], "w") as f:
            f.write("restic-pw-xyz\n")
        engine.clear_cache()
        self.app = webapp.create_app()
        self.app.testing = True
        self.c = self.app.test_client()

    def csrf(self, path="/login"):
        m = CSRF.search(self.c.get(path).get_data(as_text=True))
        self.assertIsNotNone(m, f"no csrf token on {path}")
        return m.group(1)

    def post(self, path, data, page=None):
        data = dict(data, csrf=self.csrf(page or path_page(path)))
        return self.c.post(path, data=data)

    def login(self):
        r = self.post("/login", {"password": "app-secret-pw"})
        self.assertEqual(r.status_code, 302)

    def text(self, path):
        engine.clear_cache()
        return self.c.get(path).get_data(as_text=True)


def path_page(path):
    return "/setup" if path.startswith("/setup") else "/login"


class AuthTest(Base):
    def test_everything_needs_login(self):
        for path in ("/", "/setup", "/log"):
            r = self.c.get(path)
            self.assertEqual(r.status_code, 302, path)
            self.assertIn("/login", r.headers["Location"])
        self.assertEqual(self.c.get("/api/status").status_code, 401)
        self.assertEqual(self.c.get("/healthz").status_code, 200)

    def test_post_without_csrf_rejected(self):
        self.c.get("/login")
        r = self.c.post("/login", data={"password": "app-secret-pw"})
        self.assertEqual(r.status_code, 400)
        self.assertEqual(self.c.get("/").status_code, 302)

    def test_post_actions_need_login_and_csrf(self):
        self.login()
        r = self.c.post("/setup/start", data={"path": "/Photos"})
        self.assertEqual(r.status_code, 400)
        self.assertNotIn("mega_remote_path", settings.read_file())

    def test_wrong_password_and_rate_limit(self):
        for _ in range(5):
            r = self.post("/login", {"password": "nope"})
            self.assertIn("Wrong password", r.get_data(as_text=True))
        r = self.post("/login", {"password": "app-secret-pw"})
        self.assertIn("Too many failed attempts", r.get_data(as_text=True))
        self.assertEqual(self.c.get("/").status_code, 302)

    def test_login_logout(self):
        self.login()
        self.assertEqual(self.c.get("/setup").status_code, 200)
        self.c.post("/logout", data={"csrf": self.csrf("/setup")})
        self.assertEqual(self.c.get("/setup").status_code, 302)

    def test_no_open_redirect(self):
        self.c.get("/login")
        r = self.c.post("/login?next=//evil.example/x",
                        data={"password": "app-secret-pw", "csrf": self.csrf("/login")})
        self.assertEqual(r.headers["Location"], "/")

    def test_security_headers(self):
        r = self.c.get("/login")
        self.assertIn("frame-ancestors", r.headers["Content-Security-Policy"])
        self.assertEqual(r.headers["X-Content-Type-Options"], "nosniff")

    def test_generated_app_password(self):
        os.environ.pop("APP_PASSWORD")
        try:
            pw = webapp.app_password()
            self.assertEqual(pw, webapp.app_password())
            path = os.path.join(T, "config", "app-password")
            self.assertEqual(stat.S_IMODE(os.stat(path).st_mode), 0o600)
        finally:
            os.environ["APP_PASSWORD"] = "app-secret-pw"


