"""MEGA login through MEGAcmd's interactive shell (mega-cmd) on a pseudo-terminal.

Why the shell: `mega-login email password` would put the password in the process
list, and the one-shot `mega-login email` refuses to prompt. The shell asks for the
password at a "Password:" prompt (with echo off) and passes it to the server over
its socket; the server's log redacts it. Nothing here writes the password anywhere.
"""
import re
import time

import pexpect

import engine

# Logged out the prompt is "MEGA CMD> ", logged in "<email>:<cwd>$ ". The shell
# redraws the prompt before other prompts ("MEGA CMD> Password:") and right after
# input, so a prompt alone does not mean a command has finished.
PROMPT = r"(MEGA CMD> |\S+@\S+:[^\r\n]*\$ )"
LOGGED_IN_PROMPT = r"\S+@\S+:[^\r\n]*\$ "
PASSWORD_PROMPT = r"Password:"
CODE_PROMPT = r"Enter the code generated by your authentication app: ?"
ERROR_LINE = r"(Login failed[^\r\n]*|\[(?:API:)?err[^\]]*\][^\r\n]*)"
ANSI = re.compile(r"\x1b\[[0-9;?]*[A-Za-z]|\r")

EMAIL_RE = re.compile(r"[^\s\"'\\]+@[^\s\"'\\]+\.[^\s\"'\\]+")


class LoginError(Exception):
    pass


class NeedsCode(LoginError):
    """The account has 2FA and no code was given."""


def _clean(text, secrets):
    text = ANSI.sub("", text or "")
    for s in secrets:
        if s:
            text = text.replace(s, "***")
    lines = [ln.strip() for ln in text.splitlines()]
    # Keep MEGA's messages, drop prompts and echoes.
    keep = [ln for ln in lines if ln and not re.fullmatch(PROMPT.strip() + r".*", ln)
            and not ln.startswith(("login ", "Password:"))]
    return " ".join(keep)[:500]


def check_inputs(email, password, code):
    if not EMAIL_RE.fullmatch(email or ""):
        raise LoginError("Enter a valid email address.")
    if not password:
        raise LoginError("Enter your MEGA password.")
    if any(c in password for c in "\"\\\n\r"):
        # MEGAcmd's shell puts the password in double quotes internally, so these
        # characters would be mangled.
        raise LoginError("MEGAcmd can't take passwords containing \" or \\. "
                         "Change your MEGA password, or log in from a terminal (see README).")
    if code and not re.fullmatch(r"[0-9]{6}", code):
        raise LoginError("The 2FA code is 6 digits.")


def login(email, password, code="", timeout=120, command="mega-cmd"):
    """Log in. Returns the logged-in email. Raises LoginError with a user message."""
    email = (email or "").strip()
    code = (code or "").strip()
    check_inputs(email, password, code)
    if not engine.server_running():
        raise LoginError("MEGAcmd is still starting. Try again in a few seconds.")
    if engine.whoami():
        raise LoginError("Already logged in.")

    secrets = (password, code)
    child = pexpect.spawn(command, cwd="/tmp", encoding="utf-8", codec_errors="replace",
                          timeout=timeout, dimensions=(50, 250), echo=False)
    child.logfile = None   # never record the exchange
    try:
        child.expect(PROMPT, timeout=30)
        child.sendline(f"login {email}")
        i = child.expect([PASSWORD_PROMPT, ERROR_LINE, pexpect.TIMEOUT], timeout=20)
        if i != 0:
            raise LoginError(_clean(child.after if i == 1 else child.before, secrets)
                             or "MEGAcmd did not ask for a password.")
        child.sendline(password)
        deadline = time.monotonic() + timeout
        code_sent = False
        while True:
            left = deadline - time.monotonic()
            if left <= 0:
                raise pexpect.TIMEOUT("login")
            i = child.expect([CODE_PROMPT, ERROR_LINE, LOGGED_IN_PROMPT, pexpect.TIMEOUT],
                             timeout=min(5, left))
            if i == 0:
                if not code or code_sent:
                    child.sendline("")   # answer the prompt; the login then fails
                    raise NeedsCode("This account uses two-factor authentication. "
                                    "Enter the 6-digit code.")
                child.sendline(code)
                code_sent = True
            elif i == 1:
                raise LoginError(_clean(child.after, secrets) or "Login failed.")
            elif i == 2:
                break
            else:
                # No new output for a while: ask the server directly.
                engine.clear_cache()
                if engine.whoami():
                    break
    except pexpect.TIMEOUT:
        raise LoginError("MEGA did not answer in time. Check the log, then try again.") from None
    except pexpect.EOF:
        raise LoginError("MEGAcmd's shell closed unexpectedly.") from None
    finally:
        try:
            # --only-shell: a plain `exit` would also stop the server.
            child.sendline("exit --only-shell")
            child.expect(pexpect.EOF, timeout=5)
        except (pexpect.TIMEOUT, pexpect.EOF, OSError):
            pass
        child.close(force=True)

    # The logged-in prompt can appear before the session is fully ready.
    for _ in range(10):
        engine.clear_cache()
        who = engine.whoami()
        if who:
            return who
        time.sleep(1)
    raise LoginError("MEGA accepted the login, but MEGAcmd does not show it yet. Reload in a minute.")
